// Optional integration check: requires Playwright and an available Chromium browser.
// Run against the local HTTP server: node tests/browser.cjs
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const { chromium } = require('playwright');
let browser;

(async () => {
  const executablePath = process.env.PARABOLA_BROWSER;
  browser = await chromium.launch({ headless: true, ...(executablePath ? { executablePath } : {}) });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, acceptDownloads: true });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const setRange = async (id, value) => page.locator(`#${id}`).evaluate((element, v) => { element.value = v; element.dispatchEvent(new Event('input', { bubbles: true })); }, String(value));
  await page.goto(process.env.PARABOLA_URL || 'http://127.0.0.1:4173');
  await page.evaluate(() => document.fonts.ready);
  assert.match(await page.locator('#result-range').textContent(), /63,71/);
  await page.locator('#launch').click();
  await page.waitForTimeout(350);
  await page.locator('#launch').click();
  const stoppedTime = await page.locator('#time').textContent();
  await page.waitForTimeout(150);
  assert.equal(await page.locator('#time').textContent(), stoppedTime);
  await setRange('timeline', 500);
  assert.match(await page.locator('#time').textContent(), /1,80/);
  assert.match(await page.locator('#live-x').textContent(), /31,86/);
  assert.match(await page.locator('#live-y').textContent(), /15,93/);
  await page.locator('#reset').click();
  assert.equal(await page.locator('#time').textContent(), '0,00');
  for (const angle of [30, 45, 60]) { await setRange('angle', angle); await page.locator('#save-experiment').click(); }
  assert.equal(await page.locator('#experiment-count').textContent(), '3');
  await page.locator('#compare').check();
  await page.reload();
  assert.equal(await page.locator('#experiment-count').textContent(), '3');
  const downloadEvent = page.waitForEvent('download');
  await page.locator('#export-csv').click();
  const download = await downloadEvent;
  const csv = fs.readFileSync(await download.path(), 'utf8');
  assert.equal(csv.trim().split('\n').length, 4);
  assert.match(csv, /55\.1749/);
  await page.locator('[data-delete="2"]').click();
  assert.equal(await page.locator('#experiment-count').textContent(), '2');
  await page.locator('[data-page="catatan"]').click();
  await page.locator('#notes').fill('Sudut komplementer memberi jangkauan sama pada h0 = 0.');
  await page.waitForTimeout(450);
  await page.reload();
  assert.match(await page.locator('#notes').inputValue(), /Sudut komplementer/);
  await page.locator('[data-page="panduan"]').click();
  assert.ok(await page.locator('#guide-title').isVisible());
  await page.locator('[data-page="tantangan"]').click();
  await page.locator('[data-quiz="0"][data-choice="0"]').click();
  assert.match(await page.locator('#quiz-feedback-0').textContent(), /Belum tepat/);
  await page.locator('[data-quiz="0"][data-choice="1"]').click();
  assert.match(await page.locator('#quiz-feedback-0').textContent(), /Benar/);
  await page.locator('#start-challenge').click();
  assert.ok(await page.locator('#height').isDisabled());
  assert.ok(await page.locator('#gravity').isDisabled());
  await setRange('speed', 24);
  await page.locator('#play-speed').selectOption('2');
  await page.locator('#launch').click();
  await page.waitForFunction(() => document.getElementById('sim-status').textContent === 'Mendarat', null, { timeout: 5000 });
  await page.locator('[data-page="tantangan"]').click();
  assert.match(await page.locator('#challenge-result').textContent(), /Misi berhasil/);
  await page.locator('#end-challenge').click();
  await page.locator('[data-page="simulasi"]').click();
  await page.locator('#default-params').click();
  await setRange('angle', 0);
  assert.match(await page.locator('#result-range').textContent(), /0,00/);
  assert.ok(await page.locator('#timeline').isDisabled());
  await page.locator('#launch').click();
  await setRange('angle', 90);
  assert.match(await page.locator('#result-range').textContent(), /0,00/);
  await page.locator('#gravity').selectOption('1.62');
  assert.match(await page.locator('#result-height').textContent(), /192,90/);
  await page.locator('#default-params').click();
  await setRange('angle', 60);
  await page.locator('#save-experiment').click();
  await page.locator('#default-params').click();
  await page.locator('#compare').check();
  await page.locator('#vectors').check();
  await setRange('timeline', 350);
  await page.waitForTimeout(3500);
  const directory = path.join(__dirname, '..', 'screenshots');
  fs.mkdirSync(directory, { recursive: true });
  await page.screenshot({ path: path.join(directory, 'desktop.png'), fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  const mobileContext = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, deviceScaleFactor: 2 });
  const mobile = await mobileContext.newPage();
  mobile.on('pageerror', error => errors.push(error.message));
  await mobile.goto('http://127.0.0.1:4173');
  await mobile.evaluate(() => document.fonts.ready);
  await mobile.screenshot({ path: path.join(directory, 'mobile.png') });
  assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile layout must not overflow');
  assert.ok(await mobile.locator('.time-readout').evaluate(element => element.getBoundingClientRect().right < innerWidth - 20), 'Playback time must fit inside the panel');
  await mobile.locator('[data-page="catatan"]').click();
  assert.ok(await mobile.locator('#notes').isVisible());
  // The assignment must also work without a server or a network connection.
  const offline = await browser.newContext({ offline: true });
  const filePage = await offline.newPage();
  filePage.on('pageerror', error => errors.push(error.message));
  await filePage.goto(pathToFileURL(path.join(__dirname, '..', 'index.html')).href);
  assert.match(await filePage.locator('#result-range').textContent(), /63,71/);
  await filePage.locator('#launch').click();
  await filePage.waitForTimeout(150);
  assert.notEqual(await filePage.locator('#time').textContent(), '0,00');
  assert.deepEqual(errors, [], 'No browser runtime errors');
  await browser.close();
  console.log('Lulus: animasi/jeda/reset, penggeseran waktu, penyimpanan, CSV, kuis, misi, kasus batas, desktop/mobile, dan file lokal offline.');
})().catch(async error => { console.error(error); if (browser) await browser.close(); process.exitCode = 1; });
