const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const file = path.join(__dirname, '../physics.js');
assert.ok(fs.existsSync(file), 'Model fisika harus tersedia');
const { calculate, position } = require(file);
const close = (a, b) => assert.ok(Math.abs(a - b) < 1e-8, `${a} ≠ ${b}`);
const p = { speed: 20, angle: 45, height: 0, gravity: 10 };
const r = calculate(p);
close(r.range, 40);
close(r.maxHeight, 10);
close(r.flightTime, 2 * Math.sqrt(2));
close(position(p, r.flightTime).y, 0);
close(position(p, r.apexTime).vy, 0);
close(calculate({ ...p, angle: 30 }).range, calculate({ ...p, angle: 60 }).range);
const raised = { ...p, height: 12 };
const rr = calculate(raised);
close(position(raised, rr.flightTime).y, 0);
assert.ok(rr.range > r.range);
const vertical = calculate({ ...p, angle: 90 });
assert.ok(vertical.range < 1e-10);
assert.ok(calculate({ ...p, gravity: 1.62 }).range > r.range);
assert.throws(() => calculate({ ...p, gravity: 0 }), RangeError);
assert.throws(() => calculate({ ...p, speed: NaN }), RangeError);
console.log('Lulus: solusi analitik, puncak, tumbukan, sudut komplementer, ketinggian awal, gravitasi, dan validasi.');
